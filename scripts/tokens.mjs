import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('design/tokens.json', 'utf8'));
const lines = ['/* Generated by scripts/tokens.mjs from design/tokens.json. Do not edit. */', ':root {'];
for (const [group, values] of Object.entries(tokens)) {
  if (group.startsWith('_')) continue;
  for (const [name, value] of Object.entries(values)) lines.push(`  --${group}-${name}: ${value};`);
}
lines.push('}', '');
writeFileSync('src/styles/tokens.css', lines.join('\n'));
